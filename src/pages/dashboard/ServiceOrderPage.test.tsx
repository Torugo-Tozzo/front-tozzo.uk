import { ApiError } from '@/api/errors';
vi.mock('@/contexts/AuthContext', () => import('@/test/auth-mock'));
import type { ServiceOrder } from '@/api/service-orders';
import { servicesApi } from '@/api/service-orders';
import { i18n } from '@/i18n/config';
import { renderDashboard } from '@/test/dashboard';
import { testApi as api,catalogServiceApi,replaceProperty,Route } from '@/test/service-orders-support';
import { screen,waitFor } from '@solidjs/testing-library';
import userEvent from '@testing-library/user-event';
import { afterEach,beforeEach,describe,expect,it,vi } from 'vitest';
import ServiceOrderPage from './ServiceOrderPage';
let onRealtime: () => void = () => { };

const order: ServiceOrder & {items:NonNullable<ServiceOrder["items"]>} = { id: 'o1', createdAt:'2026-09-30T10:00:00Z',totalCents:8000,acceptedQuote:null,pendingItems:[],sale:null!, customerName: 'Ana', description: 'Bike repair', status: 'APPROVED', dueAt: null, responsibleId: null, completedAt: null, updatedAt: '2026-09-30T10:00:00.000Z', items: [{ isSupplement:false,id: 'i1', productId: null, serviceId: 's1', description: 'Tune-up', details: 'Historical full description', kind: 'SERVICE', quantity: 1, unitPriceCents: 8000 }], events: [{ fromStatus: 'QUOTED', toStatus: 'APPROVED', action: 'APPROVE', createdAt: '2026-09-30T10:00:00Z', userId: 'u1' }] };
const mocks = { getOrder: vi.fn(), updateOrder: vi.fn(), action: vi.fn(), replaceQuote: vi.fn(), replaceSupplements: vi.fn(), approveSupplements: vi.fn(), list: vi.fn(), get: vi.fn() };
let restore: Array<() => void> = [];
function renderPage(mode: 'quote' | 'execution' = 'execution') {
    const result = renderDashboard('/dashboard/estimates/o1', () => <><Route path="/dashboard/estimates/:id" component={() => <ServiceOrderPage mode={mode}/>}/><Route path="/dashboard/service-orders/:id" component={() => <p>Execution destination</p>}/></>);
    onRealtime = () => { void result.queryClient.invalidateQueries({queryKey:['service-orders']}) };
    return result;
}
describe('ServiceOrderPage', () => {
    beforeEach(async () => { restore = [replaceProperty(catalogServiceApi, 'list', mocks.list as typeof catalogServiceApi.list), replaceProperty(servicesApi, 'getOrder', mocks.getOrder as typeof servicesApi.getOrder), replaceProperty(servicesApi, 'updateOrder', mocks.updateOrder as typeof servicesApi.updateOrder), replaceProperty(servicesApi, 'action', mocks.action as typeof servicesApi.action), replaceProperty(servicesApi, 'replaceQuote', mocks.replaceQuote as typeof servicesApi.replaceQuote), replaceProperty(servicesApi, 'replaceSupplements', mocks.replaceSupplements as typeof servicesApi.replaceSupplements), replaceProperty(servicesApi, 'approveSupplements', mocks.approveSupplements as typeof servicesApi.approveSupplements), replaceProperty(api, 'get', mocks.get as typeof api.get)]; await i18n.changeLanguage('en'); mocks.list.mockReset().mockResolvedValue({ items: [], total: 0 }); mocks.getOrder.mockReset().mockResolvedValue(order); mocks.updateOrder.mockReset().mockResolvedValue(order); mocks.action.mockReset().mockResolvedValue({ order: { ...order, status: 'IN_PROGRESS' }, retried: false }); mocks.replaceQuote.mockReset().mockResolvedValue({ ...order, status: 'QUOTED' }); mocks.replaceSupplements.mockReset().mockResolvedValue(order); mocks.approveSupplements.mockReset().mockResolvedValue(order); mocks.get.mockReset().mockResolvedValue({ data: { items: [], total: 0 }, headers: {} }); });
    afterEach(() => restore.forEach((fn) => fn()));
    it('never applies a previous order mutation after navigating to another id',async()=>{
        mocks.getOrder.mockImplementation((id:string)=>Promise.resolve(id==='o2'?{...order,id:'o2',customerName:'Bia'}:order));
        let finish:(value:ServiceOrder)=>void=()=>{};
        mocks.updateOrder.mockImplementationOnce(()=>new Promise<ServiceOrder>(resolve=>{finish=resolve}));
        const user=userEvent.setup();const result=renderPage();
        await user.type(await screen.findByLabelText('Customer name'),' updated');
        await user.click(screen.getByRole('button',{name:'Save details'}));
        await waitFor(()=>expect(mocks.updateOrder).toHaveBeenCalledTimes(1));
        result.history.set({value:'/dashboard/estimates/o2'});
        await waitFor(()=>expect(screen.getByLabelText('Customer name')).toHaveValue('Bia'));
        finish({...order,customerName:'Ana updated'});await Promise.resolve();
        expect(screen.getByLabelText('Customer name')).toHaveValue('Bia');
        expect(screen.getByRole('heading',{name:'Bia'})).toBeInTheDocument();
    });
    it('reloads a conflict even when the query returns the identical cached object',async()=>{
        mocks.updateOrder.mockRejectedValueOnce(new ApiError(409,{status:409,code:'SERVICE_ORDER_CONFLICT',title:'Conflict'}));
        const user=userEvent.setup();renderPage();
        const name=await screen.findByLabelText('Customer name');
        await user.type(name,' updated');
        await user.click(screen.getByRole('button',{name:'Save details'}));
        await screen.findByRole('alert');
        await user.click(screen.getByRole('button',{name:'Reload order'}));
        await waitFor(()=>expect(name).toHaveValue('Ana'));
        expect(screen.queryByRole('alert')).toBeNull();
    });
    it('cancels a realtime read started during saving before publishing the saved revision', async()=>{
        const user=userEvent.setup(); const result=renderPage();
        const name=await screen.findByLabelText('Customer name');
        let saved:(value:ServiceOrder)=>void=()=>{};
        let refreshed:(value:ServiceOrder)=>void=()=>{};
        mocks.updateOrder.mockImplementationOnce(()=>new Promise<ServiceOrder>(resolve=>{saved=resolve}));
        await user.type(name,' updated');
        await user.click(screen.getByRole('button',{name:'Save details'}));
        await waitFor(()=>expect(mocks.updateOrder).toHaveBeenCalledTimes(1));
        mocks.getOrder.mockImplementationOnce(()=>new Promise<ServiceOrder>(resolve=>{refreshed=resolve}));
        void result.queryClient.invalidateQueries({queryKey:['service-orders']});
        await waitFor(()=>expect(mocks.getOrder).toHaveBeenCalledTimes(2));
        saved({...order,customerName:'Ana updated',updatedAt:'2026-10-01T12:00:00Z'});
        await waitFor(()=>expect(result.queryClient.getQueryData<ServiceOrder>(['service-orders','detail','o1'])?.updatedAt).toBe('2026-10-01T12:00:00Z'));
        refreshed(order);await Promise.resolve();
        expect(name).toHaveValue('Ana updated');
        expect(result.queryClient.getQueryData<ServiceOrder>(['service-orders','detail','o1'])?.updatedAt).toBe('2026-10-01T12:00:00Z');
    });
    it('cancels an earlier realtime read before saving so its late result cannot restore the old revision', async () => {
        const user=userEvent.setup();
        const result=renderPage();
        const name=await screen.findByLabelText('Customer name');
        let finish:(value:ServiceOrder)=>void=()=>{};
        mocks.getOrder.mockImplementationOnce(()=>new Promise<ServiceOrder>(resolve=>{finish=resolve}));
        void result.queryClient.invalidateQueries({queryKey:['service-orders']});
        await waitFor(()=>expect(mocks.getOrder).toHaveBeenCalledTimes(2));
        mocks.updateOrder.mockResolvedValue({...order,customerName:'Ana updated',updatedAt:'2026-10-01T12:00:00Z'});
        await user.type(name,' updated');
        await user.click(screen.getByRole('button',{name:'Save details'}));
        await waitFor(()=>expect(screen.queryByRole('button',{name:'Save details'})).toBeNull());
        finish(order);
        await Promise.resolve();
        expect(name).toHaveValue('Ana updated');
        expect(result.queryClient.getQueryData<ServiceOrder>(['service-orders','detail','o1'])?.updatedAt).toBe('2026-10-01T12:00:00Z');
    });
    it('shows mixed quote lines, history and only the approved-state action', async () => { const user = userEvent.setup(); renderPage(); expect((await screen.findAllByText('Tune-up')).length).toBeGreaterThan(0); expect(screen.getByText('APPROVE · Approved')).toBeInTheDocument(); expect(screen.getByRole('button', { name: 'Start work' })).toBeInTheDocument(); expect(screen.queryByRole('button', { name: 'Close order and record sale' })).not.toBeInTheDocument(); await user.click(screen.getByRole('button', { name: 'Start work' })); await waitFor(() => expect(mocks.action).toHaveBeenCalledWith('o1', 'start', order.updatedAt)); await waitFor(() => expect(screen.queryByRole('button', {name:'Start work'})).not.toBeInTheDocument()); expect(screen.getByRole('button', {name:'Close order and record sale'})).toBeInTheDocument(); });
    it('reads accepted history independently of failed catalogs and excludes execution actions', async () => {
        mocks.get.mockRejectedValue(new Error('catalog offline'));
        mocks.getOrder.mockResolvedValue({ ...order, acceptedQuote: order.items, items: [{ ...order.items[0], description: 'Extra item', isSupplement: true }] });
        renderPage('quote');
        expect((await screen.findAllByText('Tune-up')).length).toBeGreaterThan(0);
        expect(screen.getByText('Historical full description')).toBeInTheDocument();
        expect(screen.queryByText('Extra item')).not.toBeInTheDocument();
        expect(screen.queryByRole('button', { name: 'Start work' })).not.toBeInTheDocument();
        expect(mocks.get).not.toHaveBeenCalled();
    });
    it('blocks approval while quote lines have unsaved changes and preserves them after failed save', async () => {
        const user = userEvent.setup();
        mocks.getOrder.mockResolvedValue({ ...order, status: 'QUOTED', acceptedQuote: null });
        mocks.replaceQuote.mockRejectedValueOnce(new ApiError(409,{status:409,code:'SERVICE_ORDER_CONFLICT',title:'Conflict'}));
        renderPage('quote');
        await screen.findByText('Tune-up');
        const price = screen.getByLabelText('Unit price');
        await user.clear(price);
        await user.type(price, '1245');
        expect(screen.getByRole('button', { name: 'Approve estimate' })).toBeDisabled();
        await user.click(screen.getByRole('button', { name: 'Save estimate' }));
        expect(await screen.findByRole('alert')).toHaveTextContent('This order changed elsewhere');
        expect(price).toHaveValue('12.45');
    });
    it('edits one-off labor and submits descriptions and a masked price', async () => {
        const user = userEvent.setup();
        mocks.getOrder.mockResolvedValue({ ...order, status: 'OPEN', items: [], acceptedQuote: null });
        renderPage('quote');
        await screen.findByText('Add at least one product or service.');
        await user.click(screen.getByRole('button', { name: 'Add service' }));
        await user.click(screen.getByRole('button', { name: 'Add one-off labor' }));
        await user.type(screen.getByLabelText('Item name'), 'Custom repair');
        await user.type(screen.getByLabelText('Full description'), 'Full repair instructions');
        await user.clear(screen.getByLabelText('Unit price'));
        await user.type(screen.getByLabelText('Unit price'), '1245');
        await user.click(screen.getByRole('button', { name: 'Save estimate' }));
        await waitFor(() => expect(mocks.replaceQuote).toHaveBeenCalledWith('o1', order.updatedAt, [{ description: 'Custom repair', details: 'Full repair instructions', quantity: 1, unitPriceCents: 1245 }]));
    });
    it('keeps a newly edited draft when an earlier realtime refresh resolves', async () => {
        mocks.getOrder.mockResolvedValue({ ...order, status: 'QUOTED', acceptedQuote: null });
        renderPage('quote');
        await screen.findByText('Tune-up');
        let resolveRefresh: (data: ServiceOrder) => void = () => { };
        mocks.getOrder.mockImplementationOnce(() => new Promise<ServiceOrder>((resolve) => { resolveRefresh = resolve; }));
        onRealtime();
        const user = userEvent.setup();
        const price = screen.getByLabelText('Unit price');
        await user.clear(price);
        await user.type(price, '1245');
        resolveRefresh({ ...order, status: 'QUOTED', acceptedQuote: null });
        expect(price).toHaveValue('12.45');
        expect(screen.getByRole('button', { name: 'Approve estimate' })).toBeDisabled();
    });
    it('navigates approval into execution and retains original accepted details', async () => {
        mocks.getOrder.mockResolvedValue({ ...order, status: 'QUOTED', acceptedQuote: null });
        mocks.action.mockResolvedValue({ order: { ...order, acceptedQuote: order.items } });
        renderPage('quote');
        await screen.findByText('Tune-up');
        const user = userEvent.setup();
        await user.click(screen.getByRole('button', { name: 'Approve estimate' }));
        expect(await screen.findByText('Execution destination')).toBeInTheDocument();
    });
    it('preserves supplemental drafts after failures and uses Portuguese decimal comma', async () => {
        await i18n.changeLanguage('pt-BR');
        mocks.getOrder.mockResolvedValue({ ...order, acceptedQuote: order.items });
        mocks.replaceSupplements.mockRejectedValueOnce(new ApiError(409,{status:409,code:'SERVICE_ORDER_CONFLICT',title:'Conflict'}));
        renderPage();
        await screen.findAllByText('Tune-up');
        const user = userEvent.setup();
        await user.click(screen.getByRole('button', { name: 'Editar serviços adicionais' }));
        await user.click(screen.getByRole('button', { name: 'Adicionar serviço' }));
        await user.click(screen.getByRole('button', { name: 'Adicionar mão de obra avulsa' }));
        await user.type(screen.getByLabelText('Nome do item'), 'Extra labor');
        await user.clear(screen.getByLabelText('Preço unitário'));
        await user.type(screen.getByLabelText('Preço unitário'), '1245');
        expect(screen.getByLabelText('Preço unitário')).toHaveValue('12,45');
        await user.click(screen.getByRole('button', { name: 'Solicitar aprovação do cliente' }));
        expect(await screen.findByRole('alert')).toBeInTheDocument();
        expect(screen.getByLabelText('Nome do item')).toHaveValue('Extra labor');
        expect(screen.getByLabelText('Preço unitário')).toHaveValue('12,45');
    });
    it('does not allow supplements after a linked historical sale', async () => {
        mocks.getOrder.mockResolvedValue({ ...order, acceptedQuote: order.items, sale: { id: 'sale1', total: 80, isCancelled: true } });
        renderPage();
        await screen.findAllByText('Tune-up');
        expect(screen.queryByRole('button', { name: 'Edit additional work' })).not.toBeInTheDocument();
    });
    it('blocks closing while additions await explicit client approval', async () => {
        mocks.getOrder.mockResolvedValue({ ...order, status: 'IN_PROGRESS', acceptedQuote: order.items, pendingItems: [{ ...order.items[0], description: 'Pending extra' }] });
        renderPage();
        await screen.findByText('Pending extra');
        expect(screen.getByRole('button', { name: 'Close order and record sale' })).toBeDisabled();
        const user = userEvent.setup();
        await user.click(screen.getByRole('button', { name: 'Confirm client approval' }));
        await waitFor(() => expect(mocks.approveSupplements).toHaveBeenCalledWith('o1', order.updatedAt));
    });
    it('keeps the edited draft visible and reports a 409 conflict', async () => { const user = userEvent.setup(); mocks.updateOrder.mockRejectedValueOnce(new ApiError(409,{status:409,code:'SERVICE_ORDER_CONFLICT',title:'Conflict'})); renderPage(); await screen.findAllByText('Tune-up'); const field = screen.getByLabelText('Work description'); await user.clear(field); await user.type(field, 'Revised repair'); await user.click(screen.getByRole('button', { name: 'Save details' })); expect(await screen.findByRole('alert')).toHaveTextContent('This order changed elsewhere. Reload it and try again.'); expect(field).toHaveValue('Revised repair'); });
    it('keeps open details editable and shows actions only for actual changes', async () => {
        const user = userEvent.setup();
        mocks.getOrder.mockResolvedValue({ ...order, status: 'QUOTED', acceptedQuote: null });
        renderPage('quote');
        const name = await screen.findByLabelText('Customer name');
        expect(name).toBeEnabled();
        expect(screen.getByLabelText('Work description')).toBeEnabled();
        expect(screen.queryByRole('button', { name: 'Edit details' })).not.toBeInTheDocument();
        expect(screen.queryByRole('button', { name: 'Save details' })).not.toBeInTheDocument();
        await user.clear(name);
        await user.type(name, 'Anna');
        expect(screen.getByRole('button', { name: 'Save details' })).toBeEnabled();
        expect(screen.getByRole('button', { name: 'Approve estimate' })).toBeDisabled();
        await user.clear(name);
        await user.type(name, 'Ana');
        expect(screen.queryByRole('button', { name: 'Save details' })).not.toBeInTheDocument();
        expect(screen.getByRole('button', { name: 'Approve estimate' })).toBeEnabled();
    });
    it('cancels only changed details and preserves unsaved quote lines', async () => {
        const user = userEvent.setup();
        mocks.getOrder.mockResolvedValue({ ...order, status: 'QUOTED', acceptedQuote: null });
        renderPage('quote');
        const name = await screen.findByLabelText('Customer name');
        await user.clear(screen.getByLabelText('Unit price'));
        await user.type(screen.getByLabelText('Unit price'), '1245');
        await user.type(name, ' changed');
        await user.click(screen.getByRole('button', { name: 'Cancel editing' }));
        expect(name).toHaveValue('Ana');
        expect(screen.getByLabelText('Unit price')).toHaveValue('12.45');
        expect(screen.queryByRole('button', { name: 'Save details' })).not.toBeInTheDocument();
    });
    it('protects unsaved details from a previously started realtime refresh', async () => {
        renderPage();
        const name = await screen.findByLabelText('Customer name');
        let resolveRefresh: (data: ServiceOrder) => void = () => {};
        mocks.getOrder.mockImplementationOnce(() => new Promise<ServiceOrder>(resolve => { resolveRefresh = resolve; }));
        onRealtime();
        const user = userEvent.setup();
        await user.type(name, ' edited');
        resolveRefresh(order);
        expect(name).toHaveValue('Ana edited');
        expect(screen.getByRole('button', { name: 'Save details' })).toBeEnabled();
    });

    it('saves details with the current revision while retaining unsaved quote lines', async () => {
        const user = userEvent.setup();
        const quote = { ...order, status: 'QUOTED' as const, acceptedQuote: null };
        mocks.getOrder.mockResolvedValue(quote);
        mocks.updateOrder.mockResolvedValue({ ...quote, customerName: 'Ana updated', updatedAt: '2026-10-01T12:00:00Z' });
        renderPage('quote');
        const name = await screen.findByLabelText('Customer name');
        const price = screen.getByLabelText('Unit price');
        await user.clear(price);
        await user.type(price, '1245');
        await user.type(name, ' updated');
        await user.click(screen.getByRole('button', { name: 'Save details' }));
        await waitFor(() => expect(screen.queryByRole('button', { name: 'Save details' })).not.toBeInTheDocument());
        expect(price).toHaveValue('12.45');
        await user.click(screen.getByRole('button', { name: 'Save estimate' }));
        await waitFor(() => expect(mocks.replaceQuote).toHaveBeenCalledWith('o1', '2026-10-01T12:00:00Z', expect.arrayContaining([expect.objectContaining({unitPriceCents: 1245})])));
    });
    it('keeps completed execution details read-only', async () => {
        mocks.getOrder.mockResolvedValue({ ...order, status: 'COMPLETED', acceptedQuote: order.items });
        renderPage();
        expect(await screen.findByLabelText('Customer name')).toBeDisabled();
        expect(screen.getByLabelText('Work description')).toBeDisabled();
        expect(screen.queryByRole('button', { name: 'Save details' })).not.toBeInTheDocument();
    });

});
