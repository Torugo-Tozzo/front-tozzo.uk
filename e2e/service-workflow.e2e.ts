test('quote additions work without crypto.randomUUID', async ({ page }) => {
  const fixture = await serviceWorkspace(page)
  await page.addInitScript(() => Object.defineProperty(crypto, 'randomUUID', { value: undefined, configurable: true }))
  fixture.orders.push({ id: 'order-1', establishmentId: 'tenant-1', customerName: 'Ana', description: 'Maintenance', status: 'ABERTA', dueAt: null, responsibleId: null, completedAt: null, updatedAt: '2026-10-01T12:00:00Z', acceptedQuote: null, items: [], events: [] })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/dashboard/estimates/order-1')
  await addCatalogItem(page, 'product', 'Motor oil')
  await addCatalogItem(page, 'service', 'Detailed cleaning')
  await page.getByRole('button', { name: 'Add service', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Add one-off labor' }).click()
  await page.getByLabel('Item name').fill('Emergency repair')
  await expect(page.locator('fieldset')).toHaveCount(3)
  await page.getByRole('button', { name: 'Save estimate' }).click()
  await expect(page.getByRole('button', { name: 'Approve estimate' })).toBeEnabled()
  expect(fixture.orders[0]?.items).toHaveLength(3)
  expect(errors).toEqual([])
})
