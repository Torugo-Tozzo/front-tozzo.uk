import { expect, test, type Page } from '@playwright/test'
import { serviceWorkspace } from './service-workflow.fixture'

async function addCatalogItem(page: Page, kind: 'product' | 'service', name: string) {
  await page.getByRole('button', { name: kind === 'product' ? 'Add product' : 'Add service', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: `Add ${kind} ${name}`, exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

