test('catalog supports page-long descriptions, cents and icon-only deletion', async ({ page }) => {
  const fixture = await serviceWorkspace(page)
  await page.goto('/dashboard/services')
  await expect(page.getByRole('heading', { level: 1, name: 'Service catalog' })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Service status' })).toHaveCount(0)
  await page.getByRole('button', { name: 'New service' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Service name').fill('Full detailing')
  const description = dialog.getByLabel('Description')
  await expect(description).toHaveJSProperty('tagName', 'TEXTAREA')
  await expect(description).toHaveAttribute('rows', '10')
  await description.fill(fixture.longDescription)
  await dialog.getByLabel('Reference price').fill('12345')
  await expect(dialog.getByLabel('Reference price')).toHaveValue('123.45')
  await dialog.getByRole('button', { name: 'Create service' }).click()
  const row = page.getByRole('row').filter({ hasText: 'Full detailing' })
  await expect(row).toBeVisible()
  expect(fixture.offerings[1]?.description).toBe(fixture.longDescription.trim())
  expect(fixture.offerings[1]?.referencePrice).toBe(123.45)
  const remove = row.getByRole('button', { name: 'Delete service Full detailing' })
  await expect(remove).toHaveText('')
  await expect(row.getByRole('button', { name: 'Edit service Full detailing' })).toHaveText('')
  await remove.click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete service', exact: true }).click()
  await expect(row).toHaveCount(0)
})

